// Boots core's Fastify app without listening and dumps every registered route.
// Run from the core repo root: ts-node --transpile-only <this file> <out.json>
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const CORE = process.cwd();
/* eslint-disable @typescript-eslint/no-require-imports */

// --- label preHandlers by identity, before any controller module is loaded ---
const labels = new Map<unknown, string>();
const pre = require(join(CORE, 'src/services/auth/plugins/passport/preHandlers'));
for (const [k, v] of Object.entries(pre)) if (typeof v === 'function' && k !== 'matchOne') labels.set(v, k);
const strategyNames = new Map<unknown, string>([
  [require(join(CORE, 'src/services/itemLogin/strategies/guestAccountRole')).guestAccountRole, 'guest'],
  [require(join(CORE, 'src/services/member/strategies/validatedMemberAccountRole')).validatedMemberAccountRole, 'validatedMember'],
  [require(join(CORE, 'src/services/member/strategies/memberAccountRole')).memberAccountRole, 'member'],
]);
const origMatchOne = pre.matchOne;
pre.matchOne = (...strategies: unknown[]) => {
  const fn = origMatchOne(...strategies);
  labels.set(fn, `matchOne(${strategies.map((s) => strategyNames.get(s) ?? '?').join('|')})`);
  return fn;
};
const captcha = require(join(CORE, 'src/services/auth/plugins/captcha/captcha'));
const origCaptcha = captcha.default;
captcha.default = (...args: unknown[]) => {
  const fn = origCaptcha(...args);
  labels.set(fn, `captcha(${String(args[0])})`);
  return fn;
};

const { instance } = require(join(CORE, 'src/fastify'));
// eslint-disable-next-line @typescript-eslint/no-require-imports
const registerAppPlugins = require(join(CORE, 'src/app')).default;
// eslint-disable-next-line @typescript-eslint/no-require-imports
const { queueDashboardPlugin } = require(join(CORE, 'src/workers/dashboard.controller'));

// Redis and Meilisearch are not needed to list routes; their clients reject in the
// background when those services are not running, which would otherwise crash the dump.
process.on('unhandledRejection', () => undefined);

type Row = Record<string, unknown>;
const rows: Row[] = [];

const fnNames = (h: unknown): string[] =>
  (Array.isArray(h) ? h : h ? [h] : []).map(
    (f: { name?: string }) => labels.get(f) ?? (f?.name || '<anon>'),
  );

const callerFile = (): string | undefined => {
  const frames = (new Error().stack ?? '').split('\n').slice(2);
  for (const f of frames) {
    const m = f.match(/\((.*?):(\d+):\d+\)$/) || f.match(/at (.*?):(\d+):\d+$/);
    if (!m) continue;
    const file = m[1];
    if (file.includes('node_modules') || !file.startsWith(join(CORE, 'src'))) continue;
    if (/src\/(app|fastify)\.ts$/.test(file)) continue;
    return `${file.slice(CORE.length + 1)}:${m[2]}`;
  }
  return undefined;
};

instance.addHook('onRoute', (r: Row & { schema?: Row; config?: Row }) => {
  const methods = Array.isArray(r.method) ? r.method : [r.method];
  for (const method of methods) {
    // HEAD routes are auto-generated by Fastify for every GET
    if (method === 'HEAD') continue;
    const s = (r.schema ?? {}) as Row;
    rows.push({
      method,
      url: r.url,
      websocket: Boolean(r.websocket),
      tags: s.tags ?? [],
      summary: s.summary ?? null,
      description: s.description ?? null,
      operationId: s.operationId ?? null,
      hide: s.hide ?? false,
      hasParams: Boolean(s.params),
      hasQuery: Boolean(s.querystring),
      hasBody: Boolean(s.body),
      responseCodes: s.response ? Object.keys(s.response as object) : [],
      preHandler: fnNames(r.preHandler),
      onRequest: fnNames(r.onRequest),
      preValidation: fnNames(r.preValidation),
      config: r.config ? Object.keys(r.config) : [],
      source: callerFile() ?? null,
    });
  }
});

(async () => {
  await registerAppPlugins(instance);
  await instance.register(queueDashboardPlugin);
  await instance.ready();
  const uniq = rows.filter(
    (r, i) => rows.findIndex((o) => o.method === r.method && o.url === r.url) === i,
  );
  writeFileSync(process.argv[2], JSON.stringify(uniq, null, 2));
  // eslint-disable-next-line no-console
  console.error(`dumped ${uniq.length} routes`);
  // no graceful close: Redis clients retry forever when Redis is not running
  process.exit(0);
})().catch((e) => {
  // eslint-disable-next-line no-console
  console.error(e);
  process.exit(1);
});
